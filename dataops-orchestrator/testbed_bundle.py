"""
Generates the connector bundle a testbed operator deploys: connector
properties, docker-compose, nginx vhost, a template metadata.json and a README.

Contains no data-lake credentials: the central connector supplies the (scoped)
data-lake destination in the transfer request, so the testbed never holds them.
The only secrets in the bundle are the passwords of the testbed's own Postgres
and S3 store, derived from the master secret so a regenerated bundle matches.
"""

