def _compose(tb: dict, s3_user: str, s3_password: str, pg_password: str) -> str:
    slug = tb["slug"]
    return f"""# 6G-DALI testbed connector stack: {tb['name']}
# The `rustfs` store and `rustfs-init` are optional: delete them and point the
# asset at your own S3-compatible store if you already have one.
services:

  db:
    image: postgres:16
    restart: always
    environment:
      POSTGRES_DB: edc_provider
      POSTGRES_USER: edc_user
      POSTGRES_PASSWORD: {pg_password}
    volumes:
      - DB_DATA:/var/lib/postgresql/data
    networks: [dali-net]
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U edc_user -d edc_provider"]
      interval: 10s
      timeout: 5s
      retries: 5

  rustfs:
    image: rustfs/rustfs:latest
    restart: always
    command: server /data --console-address ":9001" --address ":9000"
    environment:
      RUSTFS_ROOT_USER: {s3_user}
      RUSTFS_ROOT_PASSWORD: {s3_password}
    ports:
      - "127.0.0.1:9000:9000"
      - "127.0.0.1:9001:9001"
    volumes:
      - S3_DATA:/data
    networks: [dali-net]
    healthcheck:
      test: ["CMD-SHELL", "curl -sf http://localhost:9000/health/live || exit 1"]
      interval: 10s
      timeout: 5s
      retries: 15
      start_period: 10s

  rustfs-init:
    image: amazon/aws-cli:latest
    depends_on:
      rustfs:
        condition: service_healthy
    environment:
      AWS_ACCESS_KEY_ID: {s3_user}
      AWS_SECRET_ACCESS_KEY: {s3_password}
      AWS_DEFAULT_REGION: us-east-1
    entrypoint: >
      /bin/sh -c "aws --endpoint-url http://rustfs:9000 s3 mb s3://{slug}-datasets 2>/dev/null || true"
    networks: [dali-net]

  provider:
    image: {IMAGE}
    pull_policy: always
    restart: always
    depends_on:
      db:
        condition: service_healthy
      rustfs:
        condition: service_healthy
    # Published on the host for the nginx vhost in nginx/. Only /protocol (and
    # optionally /api) is routed publicly; the management API (18191) is not.
    ports:
      - "127.0.0.1:18190:18190"
      - "127.0.0.1:18191:18191"
      - "127.0.0.1:18192:18192"
    configs:
      - source: connector_config
        target: /usr/src/app/connector.properties
    volumes:
      - PROVIDER_DATA:/usr/src/app/data
    networks: [dali-net]

configs:
  connector_config:
    file: ./{slug}_connector.properties

networks:
  dali-net:
    driver: bridge

volumes:
  DB_DATA:
  S3_DATA:
  PROVIDER_DATA:
"""


def _nginx(tb: dict, domain: str) -> str:
    var = "edc_backend"
    return f"""# {tb['name']} EDC connector. Obtain a TLS certificate for {domain} (e.g. certbot) and
# add the usual listen 443 ssl / ssl_certificate lines.
#
#   /protocol* -> 18192 (DSP): must be public, the central connector calls it.
#   /api*      -> 18190 (health, connector UI): optional.
# The management API (18191) and control API (18193) are deliberately not published.
# The path is passed through untouched: the connector serves each API under its prefix.
map $uri ${var} {{
    default     http://127.0.0.1:18190;
    ~^/api      http://127.0.0.1:18190;
    ~^/protocol http://127.0.0.1:18192;
}}

server {{
    listen 80;
    server_name {domain};

    location ~ /.well-known {{
        root /var/www/html/;
        allow all;
    }}

    location / {{
        proxy_pass ${var};
        proxy_connect_timeout 420s;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_http_version 1.1;
        proxy_buffers 8 32k;
        proxy_buffer_size 64k;
    }}
}}
"""


